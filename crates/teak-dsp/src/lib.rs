//! The CEVA Teak DSP of the 3DS.
//!
//! This crate will be a Rust port of [Teakra](https://github.com/wwylele/teakra)
//! (MIT licence, copyright wwylele and contributors), the only public
//! low-level model of the DSP: the Teak instruction set, its memory-mapped
//! I/O, the AHBM and DMA bridges, the BTDMP audio ports and the interrupt
//! controller. The real DSP firmware from a game image runs on it.
